import transformers

text = "'Sarah loves weekends because she has plenty of time for her hobbies. She does not wake up early on Saturdays. Instead, she sleeps until noon and enjoys a quiet morning. She does not like to cook, so she orders food from her favorite restaurant. Her friends often visit her in the afternoon, but they do not stay late because everyone wants to rest for the week ahead.'"
print(text)

from transformers import pipeline
classifier = pipeline ("text-classification")

outputs = classifier(text)

import pandas as pd
pd.DataFrame(outputs)

ntext = "The sun does not shine bright today."
noutputs = classifier(ntext)
pd.DataFrame(noutputs)

ner_tagger = pipeline("ner", aggregation_strategy="simple")
outputs = ner_tagger(ntext)
pd.DataFrame(outputs)

from transformers import AutoModelForSeq2SeqLM, AutoTokenizer
model_name = "t5-small"
model= AutoModelForSeq2SeqLM.from_pretrained(model_name)
tok = AutoTokenizer.from_pretrained (model_name)
input_text = "summarize: "+ text
inputs = tok(input_text, return_tensors="pt", max_length=512, truncation=True)
summary_ids = model.generate(
    inputs ["input_ids"],
    max_length=56,
    min_length=10,
    length_penalty=2.0,
    num_beams=4,
    early_stopping=True
)
summary = tok.decode(summary_ids[0], skip_special_tokens=True, clean_up_tokenization_spaces=True)
print([{"Summary_text": summary}])

import torch
from transformers import AutoModelForQuestionAnswering, AutoTokenizer

qa_model_name = "distilbert-base-cased-distilled-squad"
qa_model = AutoModelForQuestionAnswering.from_pretrained(qa_model_name)
qa_tokenizer = AutoTokenizer.from_pretrained(qa_model_name)

question = "What keeps the doctor away?"
context = "text"

inputs = qa_tokenizer(question, context, return_tensors="pt")

with torch.no_grad():
    outputs = qa_model(**inputs)

answer_start = torch.argmax(outputs.start_logits)
answer_end = torch.argmax(outputs.end_logits) + 1

answer = qa_tokenizer.convert_tokens_to_string(
    qa_tokenizer.convert_ids_to_tokens(inputs["input_ids"][0][answer_start:answer_end])
)
print(f"Question: {question}")
print(f"Answer: {answer}")
